
package com.is.secureChatApp.service;

import tools.jackson.databind.ObjectMapper;
import com.is.secureChatApp.dto.SecureMessagePacket;
import com.is.secureChatApp.websocket.ConnectedClientRegistry;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.web.socket.TextMessage;
import org.springframework.web.socket.WebSocketSession;

import java.io.IOException;

@Service
@RequiredArgsConstructor
public class MessageRelayService {

    private final ConnectedClientRegistry clientRegistry;
    private final ObjectMapper objectMapper;

    public void relay(SecureMessagePacket packet)
            throws IOException {

        WebSocketSession recipientSession =
                clientRegistry.getSession(
                        packet.recipientUsername()
                );

        if (recipientSession == null) {
            throw new IllegalArgumentException(
                    "Recipient is not connected"
            );
        }

        // TODO (Python security integration):
        // The packet's cryptographic fields are generated by
        // the client-side Python crypto layer.
        // The server must not decrypt or modify ciphertext,
        // HMAC values, signatures, or cryptographic nonces.
        //
        // TODO (Phase 6 hardening):
        // Add message-size limits, rate limiting, delivery
        // acknowledgements, and replay protection.

        String json = objectMapper.writeValueAsString(packet);

        synchronized (recipientSession) {
            if (!recipientSession.isOpen()) {
                throw new IllegalArgumentException(
                        "Recipient disconnected before delivery"
                );
            }

            recipientSession.sendMessage(new TextMessage(json));
        }
    }
}
